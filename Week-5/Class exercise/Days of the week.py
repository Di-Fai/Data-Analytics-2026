number = int(input("Enter a number (1-7): "))

if number == 1:
    print("1 = Monday")

elif number == 2:
    print("2 = Tuesday")

elif number == 3:
    print("3 = Wednesday")

elif number == 4:
    print("4 = Thursday")

elif number == 5:
    print("5 = Friday")

elif number == 6:
    print("6 = Saturday")

elif number == 7:
    print("7 = Sunday")

else:
    print("Error:", number, "is outside the range of 1 through 7.")